"""Simulated paste + verification test.  Writes docs/SIMULATED_TEST_REPORT.md.
Everything here is a MODEL (no Minecraft available): it replays how Litematica pastes (only loaded chunks), the zone method,
the data pack's probe functions, and an independent read-back of the exported region files."""
import sys, os, re, json, subprocess, time
import numpy as np
sys.path.insert(0, os.path.dirname(__file__))
import export_world as ex, paste_kit as pk, mca, verify_world

ROOT = os.path.join(os.path.dirname(__file__), "..")
MASTER = os.path.join(ROOT, "dist", "RIFTBREK_Vanguard_Headquarters_MASTER.litematic")
PACK = os.path.join(ROOT, "datapack", "RIFTBREK_Vanguard_Datapack")
REGIONS = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "dist", "ready_world")


def main():
    t0 = time.time()
    out = ["# Simulated test report (generated by tools/simulate_paste.py)\n",
           "**These are models and static replays, NOT a Minecraft run.** They show (1) why a normal Litematica paste of this schematic ends up partial, "
           "(2) that the zone-by-zone method covers 100 %, (3) that the data pack's probe functions detect exactly the missing chunks, (4) that the ready-made world files "
           "are block-for-block identical to the schematic. Throughput figures are *assumptions*, not measurements.\n"]
    world, gpal, tiles, ents = ex.build_world_array(MASTER)
    gnames = np.array([n for n, p in gpal])
    occ = pk.nonempty_chunks(world)                                    # (Z, X) chunk occupancy
    Zc, Xc = occ.shape
    blocks_pc = (world.reshape(384, Zc, 16, Xc, 16) != 0).sum(axis=(0, 2, 4))   # solid blocks per chunk
    total_chunks = int(occ.sum()); total_blocks = int(blocks_pc.sum())
    out.append(f"## 1. What has to be pasted\n- footprint {Xc * 16} x 384 x {Zc * 16} blocks = {Xc} x {Zc} chunk grid, **{total_chunks} non-empty chunks**, {total_blocks:,} non-air blocks, "
               f"{len(tiles):,} tile entities, {len(ents)} entities.\n- Litematica only places blocks in chunks the server has **loaded**. A player standing at the origin loads a square of "
               "(2R+1)^2 chunks (R = view/simulation distance).\n")
    # ---- A. Litematica default behaviour
    out.append("## 2. Simulated Litematica paste standing still at the schematic origin / centre\n\n| standing at | R (chunks) | chunks pasted | % of chunks | % of blocks |\n|---|---|---|---|---|")
    def covered(cx, cz, R):
        m = np.zeros_like(occ)
        m[max(0, cz - R):cz + R + 1, max(0, cx - R):cx + R + 1] = True
        return m & occ
    for (lab, cx, cz) in (("origin (0,0)", 0, 0), ("HQ centre", 24, 24), ("annex centre", 90, 18)):
        for R in (8, 12, 16, 32):
            m = covered(cx, cz, R)
            out.append(f"| {lab} | {R} | {int(m.sum())} / {total_chunks} | {100 * m.sum() / total_chunks:.0f}% | {100 * blocks_pc[m].sum() / total_blocks:.0f}% |")
    out.append("\n=> A single paste can never reach 100 %: even R=32 from the origin pastes a minority of the schematic. The part that is missing is every chunk that was not loaded. "
               "This matches \"it didn't fully paste in\".\n")
    # ---- B. zone method
    zones = pk.plan(world)
    out.append(f"## 3. Zone-by-zone method ({len(zones)} zones of <= 16x16 chunks = the /forceload limit)\n\n| zone | chunks | blocks | est. paste time @50k blk/s | @200k blk/s |\n|---|---|---|---|---|")
    done = np.zeros_like(occ); cum = []
    for z in zones:
        rect = np.zeros_like(occ); rect[z["cz0"]:z["cz1"] + 1, z["cx0"]:z["cx1"] + 1] = True
        rect &= occ
        done |= rect
        b = int(blocks_pc[rect].sum())
        out.append(f"| {z['n']} | {int(rect.sum())} | {b:,} | {b / 50000 / 60:.1f} min | {b / 200000 / 60:.1f} min |")
        cum.append(100 * done.sum() / total_chunks)
    tot_b = total_blocks
    out.append(f"\n- Cumulative chunk coverage after each pass: {', '.join(f'{c:.0f}%' for c in cum)}. **Final: {cum[-1]:.0f}%**.\n"
               f"- Total estimated paste time (assumed throughput only): {tot_b / 50000 / 60:.0f} min at 50k blocks/s, {tot_b / 200000 / 60:.0f} min at 200k blocks/s.\n")
    # ---- C. probes vs partial states
    out.append("## 4. Probe functions (`riftbrek:paste/zone_N_check`) replayed against partial pastes\n")
    def parse_probes(fn):
        pr = []; cur = []
        for ln in open(fn).read().split("\n"):
            m = re.match(r"\$execute positioned \$\(x\) (-?\d+) \$\(z\) if block ~(-?\d+) ~ ~(-?\d+) (\S+) run scoreboard players add #c", ln)
            if m:
                cur.append((int(m.group(2)), int(m.group(1)), int(m.group(3)), m.group(4)))
            elif ln.startswith("scoreboard players add #TOT"):
                pr.append(cur); cur = []
        return pr
    def name_at(loaded_mask, x, wy, z):
        ly = wy + 64
        if not (0 <= ly < 384 and 0 <= x < Xc * 16 and 0 <= z < Zc * 16):
            return "minecraft:air"
        if not loaded_mask[z >> 4, x >> 4]:
            return "minecraft:air"
        return gnames[world[ly, z, x]]
    rng = np.random.default_rng(1)
    scen = {"nothing pasted": np.zeros_like(occ), "default paste at origin, R=12": covered(0, 0, 12),
            "random 70% of chunks": (rng.random(occ.shape) < 0.7) & occ, "everything pasted": occ.copy()}
    out.append("| scenario | chunks truly missing | reported missing | false alarms | undetected |\n|---|---|---|---|---|")
    for sname, mask in scen.items():
        truly = int((occ & ~mask).sum()); rep = 0; fa = 0; und = 0
        for z in zones:
            probes = parse_probes(os.path.join(PACK, "data/riftbrek/function/paste", f"zone_{z['n']}_check.mcfunction"))
            chunks = [c for c in z["chunks"] if pk.probes_for_chunk(world, gpal, *c)]
            assert len(chunks) == len(probes), (z["n"], len(chunks), len(probes))
            for (cx, cz), pr in zip(chunks, probes):
                ok = all(name_at(mask, px, py, pz) == nm for (px, py, pz, nm) in pr)
                present = bool(mask[cz, cx])
                if not ok:
                    rep += 1
                if ok and not present:
                    und += 1
                if (not ok) and present:
                    fa += 1
        out.append(f"| {sname} | {truly} | {rep} | {fa} | {und} |")
    out.append("\n(`undetected` = a chunk that is missing but whose probes all pass, e.g. a probe block identical to void; `false alarms` must be 0.)\n")
    # ---- D. admin/verify against exported regions
    out.append("## 5. `riftbrek:admin/verify` replayed against the exported world files\n")
    vlines = [l for l in open(os.path.join(PACK, "data/riftbrek/function/admin/verify_do.mcfunction")).read().split("\n") if "if block" in l and " unless " not in l]
    cache = {}
    def region_block(x, wy, z):
        cx, cz = x >> 4, z >> 4
        k = (cx, cz)
        if k not in cache:
            f = os.path.join(REGIONS, "region", f"r.{cx >> 5}.{cz >> 5}.mca")
            import struct, zlib
            d = open(f, "rb").read(); i = (cx & 31) + (cz & 31) * 32
            off = struct.unpack(">I", b"\0" + d[i * 4:i * 4 + 3])[0]
            ln, comp = struct.unpack(">IB", d[off * 4096:off * 4096 + 5])
            cache[k] = mca.nbt.loads(zlib.decompress(d[off * 4096 + 5:off * 4096 + 4 + ln]))
        c = cache[k]
        sec = [s for s in c["sections"] if s["Y"] == (wy >> 4)][0]
        pal, arr = mca.unpack_section(sec)
        return pal[int(arr[wy & 15, z & 15, x & 15])][0]
    ok = 0
    for ln in vlines:
        m = re.match(r"\$execute positioned \$\(x\) (-?\d+) \$\(z\) if block ~(-?\d+) ~ ~(-?\d+) (\S+) run", ln)
        wy, dx, dz, nm = int(m.group(1)), int(m.group(2)), int(m.group(3)), m.group(4)
        got = region_block(dx, wy, dz)
        label = re.search(r'"text":"PASS  ([^"]+)"', ln).group(1)
        res = got == nm
        ok += res
        out.append(f"- {'PASS' if res else 'FAIL'}  {label}: expected `{nm}` at ({dx},{wy},{dz}), file has `{got}`")
    out.append(f"\n**{ok} / {len(vlines)} verify probes pass** against the region files (origin X=0, Z=0).\n")
    # ---- E. region export read-back
    out.append("## 6. Ready-made world files: independent read-back vs the master schematic\n```")
    import io, contextlib
    buf = io.StringIO()
    with contextlib.redirect_stdout(buf):
        rb = verify_world.main(MASTER, REGIONS)
    out.append("\n".join(l for l in buf.getvalue().split("\n") if l.startswith(("chunks", "RESULT", "region headers"))))
    out.append("```\n")
    # ---- F. data pack + logic suites
    out.append("## 7. Data pack suites re-run now\n```")
    for cmd in ([sys.executable, "-I", os.path.join(ROOT, "tools", "validate.py"), PACK],
                [sys.executable, "-I", os.path.join(ROOT, "tools", "model_test.py"), PACK]):
        r = subprocess.run(cmd, capture_output=True, text=True)
        lines = [l for l in r.stdout.split("\n") if l.startswith(("functions", "FAILED")) or "FAIL" in l]
        out.append(" ".join(os.path.basename(cmd[2]).split()) + ": " + " | ".join(lines))
    out.append("```\n")
    out.append("## 8. Still NOT verifiable here\nBehaviour inside the real game: that Minecraft accepts the region files without complaint (format follows the 1.21.11 chunk layout and was read back with a reader validated on a genuine 1.19.2 save), "
               "that command blocks/hoppers/redstone work, that imported builds work in 1.21.11, performance with ~1,900 blimp entities.\n")
    out.append(f"_generated in {time.time() - t0:.0f}s_\n")
    open(os.path.join(ROOT, "docs", "SIMULATED_TEST_REPORT.md"), "w").write("\n".join(out))
    print("\n".join(out)[:200]); print("written; verify_world ok =", rb)


if __name__ == "__main__":
    main()
